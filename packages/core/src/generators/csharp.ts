import type { BinaryOp, CallExpr, Expr } from '../ast';
import type { CompiledProgram } from '../bytecode';
import type { BaseType, TypedBlock, TypedProgram } from '../ir';
import { Emitter } from './js';

export interface CSharpOptions {
  indent?: string;
}

/**
 * C# generator. The chart's types map directly: int → int, real → double, string → string,
 * bool → bool, arrays → T[]. Everything that is culture-sensitive in .NET goes through
 * CultureInfo.InvariantCulture, because on a Turkish Windows "2.5" prints as "2,5" and
 * "i".ToUpper() is "İ".
 *
 *   Fmt(double)    shortest round-trip formatting matching the interpreter ("5" not "5.0", "0.00001" not "1E-05")
 *   (double)a / b  the chart's `/` is always real division; C#'s int / int truncates
 *   a / b          `div` on ints: C# already truncates toward zero
 *   a % b          sign of the dividend in C#, same as the interpreter
 *   (int)Math.Floor(x + 0.5)   JS-style rounding; Math.Round is banker's rounding
 *   string.CompareOrdinal      C# has no < > on strings
 */
export function generateCSharp(compiled: CompiledProgram, options: CSharpOptions = {}): string {
  return new CSharpGenerator(options.indent ?? '    ').generate(compiled.typed);
}

interface Needs {
  fmt: boolean;
  globalization: boolean;
  utf8: boolean;
}

const PREC: Record<BinaryOp, number> = {
  or: 1, and: 2,
  '==': 3, '!=': 3,
  '<': 4, '<=': 4, '>': 4, '>=': 4,
  '+': 5, '-': 5,
  '*': 6, '/': 6, '%': 6, div: 6,
  '^': 10, // Math.Pow(...)
};
const UNARY = 7; // also casts
const ATOM = 10;

const OPS: Partial<Record<BinaryOp, string>> = { and: '&&', or: '||', div: '/' };

const paren = (s: string): string => `(${s})`;
const baseOf = (e: Expr): BaseType | undefined => (e.type?.kind === 'scalar' ? e.type.base : undefined);
const isInt = (e: Expr): boolean => baseOf(e) === 'int';
const isString = (e: Expr): boolean => baseOf(e) === 'string';
/** ints and strings print identically; doubles and bools need Fmt(). */
const needsFmt = (e: Expr): boolean => baseOf(e) === 'real' || baseOf(e) === 'bool';

function precOf(e: Expr): number {
  if (e.kind === 'binary') return e.op === '^' && isInt(e) ? UNARY : PREC[e.op]; // (int)Math.Pow(...) is a cast
  if (e.kind === 'unary') return UNARY;
  if (e.kind === 'call' && (e.name === 'floor' || e.name === 'ceil' || e.name === 'round')) return UNARY; // (int)Math.X(...)
  return ATOM;
}

export function csType(type: BaseType, array = false): string {
  const base = type === 'real' ? 'double' : type;
  return array ? `${base}[]` : base;
}

class CSharpGenerator {
  private readonly needs: Needs = { fmt: false, globalization: false, utf8: false };
  private out: Emitter;

  constructor(private readonly indent: string) {
    this.out = new Emitter(indent);
  }

  generate(program: TypedProgram): string {
    const body = this.out;
    body.block(() => {
      for (const fn of program.functions) {
        const params = fn.params.map((p) => `${csType(p.type, p.array === true)} ${p.name}`).join(', ');
        body.line(`static ${fn.returns ? csType(fn.returns) : 'void'} ${fn.name}(${params})`);
        body.line('{');
        body.block(() => this.statements(fn.body));
        body.line('}');
        body.line();
      }
      body.line('static void Main()');
      body.line('{');
      body.block(() => {
        if (this.hasNonAscii(program)) {
          this.needs.utf8 = true;
          body.line('Console.OutputEncoding = new UTF8Encoding(false);');
        }
        this.statements(program.main);
      });
      body.line('}');
    });

    // The header depends on what the body used, so it is assembled last.
    const head = new Emitter(this.indent);
    head.line('// Generated by FlowCode — C#');
    head.line('using System;');
    if (this.needs.globalization || this.needs.fmt) head.line('using System.Globalization;');
    if (this.needs.utf8) head.line('using System.Text;');
    head.line();
    head.line('class Program');
    head.line('{');
    if (this.needs.fmt) {
      head.block(() => {
        for (const line of FMT_HELPER) head.line(line);
      });
      head.line();
    }
    return head.toString() + body.toString() + '}\n';
  }

  private hasNonAscii(program: TypedProgram): boolean {
    const visitExpr = (e: Expr): boolean => {
      switch (e.kind) {
        case 'str': return /[^\x00-\x7f]/.test(e.value);
        case 'index': return visitExpr(e.index);
        case 'unary': return visitExpr(e.operand);
        case 'binary': return visitExpr(e.left) || visitExpr(e.right);
        case 'call': return e.args.some(visitExpr);
        default: return false;
      }
    };
    const visit = (blocks: TypedBlock[]): boolean =>
      blocks.some((b) => {
        switch (b.kind) {
          case 'declare': return b.size ? visitExpr(b.size) : false;
          case 'assign': return visitExpr(b.value) || (b.index ? visitExpr(b.index) : false);
          case 'output': return visitExpr(b.value);
          case 'if': return visitExpr(b.condition) || visit(b.then) || visit(b.else);
          case 'while': case 'doWhile': return visitExpr(b.condition) || visit(b.body);
          case 'for': return visitExpr(b.from) || visitExpr(b.to) || visit(b.body);
          case 'call': return b.args.some(visitExpr);
          case 'return': return b.value ? visitExpr(b.value) : false;
          default: return false;
        }
      });
    return visit(program.main) || program.functions.some((f) => visit(f.body));
  }

  // ---------------------------------------------------------------------------
  // Statements

  private statements(blocks: TypedBlock[]): void {
    for (const b of blocks) this.statement(b);
  }

  private statement(b: TypedBlock): void {
    const out = this.out;
    const nested = (blocks: TypedBlock[]): void => {
      out.line('{');
      out.block(() => this.statements(blocks));
      out.line('}');
    };

    switch (b.kind) {
      case 'comment':
        for (const line of b.text.split('\n')) out.line(`// ${line}`);
        return;

      case 'declare':
        if (b.size) {
          out.line(`${csType(b.type, true)} ${b.name} = new ${csType(b.type)}[${this.expr(b.size)}];`);
          if (b.type === 'string') out.line(`Array.Fill(${b.name}, "");`);
        } else {
          out.line(`${csType(b.type)} ${b.name} = ${defaultLiteral(b.type)};`);
        }
        return;

      case 'assign':
        out.line(`${this.lvalue(b.target, b.index)} = ${this.expr(b.value)};`);
        return;

      case 'input':
        out.line(`${this.lvalue(b.target, b.index)} = ${this.readExpr(b.type!)};`);
        return;

      case 'output':
        out.line(`Console.${b.newline === false ? 'Write' : 'WriteLine'}(${this.printable(b.value)});`);
        return;

      case 'if': {
        out.line(`if (${this.expr(b.condition)})`);
        nested(b.then);
        let elseBlocks = b.else;
        while (elseBlocks.length === 1 && elseBlocks[0].kind === 'if') {
          const chained = elseBlocks[0];
          out.line(`else if (${this.expr(chained.condition)})`);
          nested(chained.then);
          elseBlocks = chained.else;
        }
        if (elseBlocks.length) {
          out.line('else');
          nested(elseBlocks);
        }
        return;
      }

      case 'while':
        out.line(`while (${this.expr(b.condition)})`);
        nested(b.body);
        return;

      case 'doWhile':
        out.line('do');
        nested(b.body);
        out.line(`while (${this.expr(b.condition)});`);
        return;

      case 'for': {
        const step = b.step ?? 1;
        const v = b.variable;
        const update = step === 1 ? `${v}++` : step === -1 ? `${v}--` : step > 0 ? `${v} += ${step}` : `${v} -= ${-step}`;
        out.line(`for (${v} = ${this.expr(b.from)}; ${v} ${step > 0 ? '<=' : '>='} ${this.expr(b.to)}; ${update})`);
        nested(b.body);
        return;
      }

      case 'call':
        out.line(`${b.name}(${b.args.map((a) => this.expr(a)).join(', ')});`);
        return;

      case 'break':
        out.line('break;');
        return;

      case 'return':
        out.line(b.value ? `return ${this.expr(b.value)};` : 'return;');
        return;
    }
  }

  private lvalue(name: string, index?: Expr): string {
    return index ? `${name}[${this.expr(index)}]` : name;
  }

  private readExpr(type: BaseType): string {
    switch (type) {
      case 'int':
        return 'int.Parse(Console.ReadLine() ?? "")';
      case 'real':
        this.needs.globalization = true;
        return 'double.Parse(Console.ReadLine() ?? "", CultureInfo.InvariantCulture)';
      case 'bool':
        return '(Console.ReadLine() ?? "").Trim() == "true"';
      case 'string':
        return 'Console.ReadLine() ?? ""';
    }
  }

  private printable(e: Expr): string {
    if (!needsFmt(e)) return this.expr(e);
    this.needs.fmt = true;
    return `Fmt(${this.expr(e)})`;
  }

  // ---------------------------------------------------------------------------
  // Expressions

  private operand(e: Expr, parentPrec: number, side: 'left' | 'right'): string {
    const p = precOf(e);
    const needsParens = side === 'left' ? p < parentPrec : p <= parentPrec;
    return needsParens ? paren(this.expr(e)) : this.expr(e);
  }

  /** Operand of a cast or unary operator. */
  private unaryOperand(e: Expr): string {
    return precOf(e) < UNARY ? paren(this.expr(e)) : this.expr(e);
  }

  private postfixTarget(e: Expr): string {
    return precOf(e) < ATOM ? paren(this.expr(e)) : this.expr(e);
  }

  private expr(e: Expr): string {
    switch (e.kind) {
      case 'num':
        return e.text;
      case 'str':
        return JSON.stringify(e.value);
      case 'bool':
        return e.value ? 'true' : 'false';
      case 'var':
        return e.name;
      case 'index':
        // Indexing a string must stay a string; C#'s s[i] is a char.
        return e.targetType?.kind === 'scalar' ? `${e.name}.Substring(${this.expr(e.index)}, 1)` : `${e.name}[${this.expr(e.index)}]`;
      case 'unary': {
        const doubleMinus = e.op === '-' && e.operand.kind === 'unary' && e.operand.op === '-';
        const inner = doubleMinus ? paren(this.expr(e.operand)) : this.unaryOperand(e.operand);
        return (e.op === 'not' ? '!' : '-') + inner;
      }
      case 'binary':
        return this.binary(e);
      case 'call':
        return this.builtinCall(e) ?? `${e.name}(${e.args.map((a) => this.expr(a)).join(', ')})`;
    }
  }

  private binary(e: Expr & { kind: 'binary' }): string {
    const { op, left, right } = e;

    if (op === '^') {
      const pow = `Math.Pow(${this.expr(left)}, ${this.expr(right)})`;
      return isInt(e) ? `(int)${pow}` : pow;
    }

    if (op === '/' && isInt(left) && isInt(right)) {
      // Real division of two ints: a literal becomes 7.0, anything else gets a cast.
      const numerator = left.kind === 'num' ? `${left.text}.0` : `(double)${this.unaryOperand(left)}`;
      return `${numerator} / ${this.operand(right, PREC['/'], 'right')}`;
    }

    if (PREC[op] === 4 && isString(left) && isString(right)) {
      return `string.CompareOrdinal(${this.expr(left)}, ${this.expr(right)}) ${op} 0`;
    }

    if (op === '+' && isString(e)) {
      return `${this.concatOperand(left, 'left')} + ${this.concatOperand(right, 'right')}`;
    }

    const p = PREC[op];
    // `a < b == c` is legal C# but reads as a typo; keep the chart's parentheses around comparisons.
    const wrapComparison = (side: Expr, text: string): string => (p === 3 && precOf(side) === 4 ? paren(text) : text);
    const l = wrapComparison(left, this.operand(left, p, 'left'));
    const r = wrapComparison(right, this.operand(right, p, 'right'));
    return `${l} ${OPS[op] ?? op} ${r}`;
  }

  /** In a concatenation, arithmetic operands keep their parentheses: `"sum = " + (a + b)`, never `"x = " + -7 % 3`. */
  private concatOperand(e: Expr, side: 'left' | 'right'): string {
    if (needsFmt(e)) {
      this.needs.fmt = true;
      return `Fmt(${this.expr(e)})`;
    }
    if (e.kind === 'binary' && !isString(e)) return paren(this.expr(e));
    return this.operand(e, PREC['+'], side);
  }

  private builtinCall(e: CallExpr): string | undefined {
    const args = e.args.map((a) => this.expr(a));
    switch (e.name) {
      case 'len':
        return `${this.postfixTarget(e.args[0])}.Length`;
      case 'abs':
      case 'sqrt':
      case 'min':
      case 'max':
      case 'pow':
        return `Math.${e.name[0].toUpperCase()}${e.name.slice(1)}(${args.join(', ')})`;
      case 'floor':
      case 'ceil':
        return `(int)Math.${e.name === 'floor' ? 'Floor' : 'Ceiling'}(${args[0]})`;
      case 'round':
        return `(int)Math.Floor(${this.operand(e.args[0], PREC['+'], 'left')} + 0.5)`;
      case 'toInt':
        return `int.Parse(${args[0]})`;
      case 'toReal':
        this.needs.globalization = true;
        return `double.Parse(${args[0]}, CultureInfo.InvariantCulture)`;
      case 'toString':
        this.needs.fmt = true;
        return `Fmt(${args[0]})`;
      case 'upper':
        return `${this.postfixTarget(e.args[0])}.ToUpperInvariant()`;
      case 'lower':
        return `${this.postfixTarget(e.args[0])}.ToLowerInvariant()`;
      default:
        return undefined;
    }
  }
}

function defaultLiteral(type: BaseType): string {
  switch (type) {
    case 'int': return '0';
    case 'real': return '0.0';
    case 'string': return '""';
    case 'bool': return 'false';
  }
}

const FMT_HELPER = [
  '// Formats values the way the FlowCode interpreter prints them.',
  'static string Fmt(double value)',
  '{',
  '    if (double.IsNaN(value)) return "NaN";',
  '    if (double.IsInfinity(value)) return value > 0 ? "Infinity" : "-Infinity";',
  '    if (value == 0) return "0";',
  '    if (value == Math.Floor(value) && Math.Abs(value) < 1e21) return value.ToString("F0", CultureInfo.InvariantCulture);',
  '    string text = value.ToString("R", CultureInfo.InvariantCulture);',
  '    int e = text.IndexOf(\'E\');',
  '    if (e < 0) return text;',
  '    if (Math.Abs(value) >= 1e-6) return decimal.Parse(text, NumberStyles.Float, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture);',
  '    string exponent = text.Substring(e + 2).TrimStart(\'0\');',
  '    return text.Substring(0, e) + "e" + text[e + 1] + (exponent.Length == 0 ? "0" : exponent);',
  '}',
  '',
  'static string Fmt(bool value) => value ? "true" : "false";',
  'static string Fmt(int value) => value.ToString(CultureInfo.InvariantCulture);',
  'static string Fmt(string value) => value;',
];
