import type { BinaryOp, CallExpr, Expr } from '../ast';
import type { CompiledProgram } from '../bytecode';
import type { BaseType, TypedBlock, TypedProgram } from '../ir';

export interface JsOptions {
  /** 'node' reads stdin and writes stdout; 'browser' uses prompt() and console.log(). Default 'node'. */
  runtime?: 'node' | 'browser';
  indent?: string;
}

/** JavaScript and TypeScript share one walker; the dialect only adds type annotations and imports. */
export interface Dialect {
  typescript: boolean;
}

export function generateJs(compiled: CompiledProgram, options: JsOptions = {}): string {
  return generateJsLike(compiled, options, { typescript: false });
}

export function generateJsLike(compiled: CompiledProgram, options: JsOptions, dialect: Dialect): string {
  const runtime = options.runtime ?? 'node';
  const out = new Emitter(options.indent ?? '  ');
  const program = compiled.typed;
  const uses = scanUsage(program);
  const ts = dialect.typescript;
  const t = (annotation: string): string => (ts ? annotation : '');

  out.line(`// Generated by FlowCode — ${ts ? 'TypeScript' : 'JavaScript'} (${runtime === 'node' ? 'Node.js' : 'browser'})`);
  // A .ts file without import/export is a script in the global scope, so two generated files
  // in one project would collide. `export {}` makes it a module with its own scope.
  if (ts && !(runtime === 'node' && uses.input)) out.line('export {};');
  if (runtime === 'node') {
    if (uses.input) {
      if (ts) {
        out.line('import { readFileSync } from "node:fs";');
        out.line();
        out.line('const __lines: string[] = readFileSync(0, "utf8").split(/\\r?\\n/);');
      } else {
        out.line('const __lines = require("fs").readFileSync(0, "utf8").split(/\\r?\\n/);');
      }
      out.line('let __lineIndex = 0;');
      out.line(`function readLine()${t(': string')} { return __lines[__lineIndex++] ?? ""; }`);
    }
    if (uses.write) out.line(`function write(value${t(': unknown')})${t(': void')} { process.stdout.write(String(value)); }`);
    if (uses.writeln) out.line(`function writeln(value${t(': unknown')})${t(': void')} { process.stdout.write(String(value) + "\\n"); }`);
  } else {
    if (uses.input || uses.write || uses.writeln) out.line('let __buffer = "";');
    if (uses.input) out.line(`function readLine()${t(': string')} { const text = prompt(__buffer) ?? ""; __buffer = ""; return text; }`);
    if (uses.write) out.line(`function write(value${t(': unknown')})${t(': void')} { __buffer += String(value); }`);
    if (uses.writeln) out.line(`function writeln(value${t(': unknown')})${t(': void')} { console.log(__buffer + String(value)); __buffer = ""; }`);
  }

  for (const fn of program.functions) {
    const params = fn.params.map((p) => (ts ? `${p.name}: ${tsType(p.type, p.array === true)}` : p.name)).join(', ');
    out.line();
    out.line(`function ${fn.name}(${params})${t(fn.returns ? `: ${tsType(fn.returns)}` : ': void')} {`);
    out.block(() => statements(fn.body, out, dialect));
    out.line('}');
  }

  out.line();
  out.line(`function main()${t(': void')} {`);
  out.block(() => statements(program.main, out, dialect));
  out.line('}');
  out.line();
  out.line('main();');

  return out.toString();
}

function tsType(type: BaseType, array = false): string {
  const base = type === 'string' ? 'string' : type === 'bool' ? 'boolean' : 'number';
  return array ? `${base}[]` : base;
}

// ---------------------------------------------------------------------------
// Statements

function statements(blocks: TypedBlock[], out: Emitter, dialect: Dialect): void {
  for (const b of blocks) statement(b, out, dialect);
}

function statement(b: TypedBlock, out: Emitter, dialect: Dialect): void {
  const nested = (blocks: TypedBlock[]): void => out.block(() => statements(blocks, out, dialect));
  switch (b.kind) {
    case 'comment':
      for (const line of b.text.split('\n')) out.line(`// ${line}`);
      return;

    case 'declare': {
      const annotation = dialect.typescript ? `: ${tsType(b.type, b.size !== undefined)}` : '';
      if (b.size) out.line(`let ${b.name}${annotation} = new Array(${expr(b.size)}).fill(${defaultLiteral(b.type)});`);
      else out.line(`let ${b.name}${annotation} = ${defaultLiteral(b.type)};`);
      return;
    }

    case 'assign':
      out.line(`${lvalue(b.target, b.index)} = ${expr(b.value)};`);
      return;

    case 'input':
      out.line(`${lvalue(b.target, b.index)} = ${readExpr(b.type!)};`);
      return;

    case 'output':
      out.line(`${b.newline === false ? 'write' : 'writeln'}(${expr(b.value)});`);
      return;

    case 'if': {
      out.line(`if (${expr(b.condition)}) {`);
      nested(b.then);
      let elseBlocks = b.else;
      while (elseBlocks.length === 1 && elseBlocks[0].kind === 'if') {
        const chained = elseBlocks[0];
        out.line(`} else if (${expr(chained.condition)}) {`);
        nested(chained.then);
        elseBlocks = chained.else;
      }
      if (elseBlocks.length) {
        out.line('} else {');
        nested(elseBlocks);
      }
      out.line('}');
      return;
    }

    case 'while':
      out.line(`while (${expr(b.condition)}) {`);
      nested(b.body);
      out.line('}');
      return;

    case 'doWhile':
      out.line('do {');
      nested(b.body);
      out.line(`} while (${expr(b.condition)});`);
      return;

    case 'for': {
      const step = b.step ?? 1;
      const v = b.variable;
      const update = step === 1 ? `${v}++` : step === -1 ? `${v}--` : step > 0 ? `${v} += ${step}` : `${v} -= ${-step}`;
      out.line(`for (${v} = ${expr(b.from)}; ${v} ${step > 0 ? '<=' : '>='} ${expr(b.to)}; ${update}) {`);
      nested(b.body);
      out.line('}');
      return;
    }

    case 'call':
      out.line(`${b.name}(${b.args.map(expr).join(', ')});`);
      return;

    case 'break':
      out.line('break;');
      return;

    case 'return':
      out.line(b.value ? `return ${expr(b.value)};` : 'return;');
      return;
  }
}

const lvalue = (name: string, index?: Expr): string => (index ? `${name}[${expr(index)}]` : name);

function defaultLiteral(type: BaseType): string {
  switch (type) {
    case 'int':
    case 'real':
      return '0';
    case 'string':
      return '""';
    case 'bool':
      return 'false';
  }
}

function readExpr(type: BaseType): string {
  switch (type) {
    case 'int':
      return 'parseInt(readLine(), 10)';
    case 'real':
      return 'parseFloat(readLine())';
    case 'bool':
      return 'readLine().trim() === "true"';
    case 'string':
      return 'readLine()';
  }
}

// ---------------------------------------------------------------------------
// Expressions

const PREC: Record<BinaryOp, number> = {
  or: 1, and: 2,
  '==': 3, '!=': 3,
  '<': 4, '<=': 4, '>': 4, '>=': 4,
  '+': 5, '-': 5,
  '*': 6, '/': 6, '%': 6,
  '^': 7,
  div: 10, // emitted as Math.trunc(...)
};

const OPS: Record<BinaryOp, string> = {
  and: '&&', or: '||', '==': '===', '!=': '!==',
  '<': '<', '<=': '<=', '>': '>', '>=': '>=',
  '+': '+', '-': '-', '*': '*', '/': '/', '%': '%', '^': '**', div: '/',
};

function precOf(e: Expr): number {
  if (e.kind === 'binary') return PREC[e.op];
  if (e.kind === 'unary') return 8;
  return 10;
}

const paren = (s: string): string => `(${s})`;

function operand(e: Expr, parentPrec: number, side: 'left' | 'right'): string {
  const p = precOf(e);
  const needsParens = side === 'left' ? p < parentPrec : p <= parentPrec;
  return needsParens ? paren(expr(e)) : expr(e);
}

/** Wrap anything that isn't atomic, for `.length` / `.toUpperCase()` style access. */
const postfixTarget = (e: Expr): string => (precOf(e) < 10 ? paren(expr(e)) : expr(e));

export function expr(e: Expr): string {
  switch (e.kind) {
    case 'num':
      return e.text;
    case 'str':
      return JSON.stringify(e.value);
    case 'bool':
      return e.value ? 'true' : 'false';
    case 'var':
      return e.name;
    case 'index':
      return `${e.name}[${expr(e.index)}]`;
    case 'unary': {
      const doubleMinus = e.op === '-' && e.operand.kind === 'unary' && e.operand.op === '-';
      const inner = precOf(e.operand) < 8 || doubleMinus ? paren(expr(e.operand)) : expr(e.operand);
      return (e.op === 'not' ? '!' : '-') + inner;
    }
    case 'binary': {
      if (e.op === 'div') return `Math.trunc(${operand(e.left, 6, 'left')} / ${operand(e.right, 6, 'right')})`;
      if (e.op === '^') {
        // JS forbids a unary operator directly left of ** and ** is right-associative.
        const left = precOf(e.left) <= 8 ? paren(expr(e.left)) : expr(e.left);
        const right = precOf(e.right) < 7 ? paren(expr(e.right)) : expr(e.right);
        return `${left} ** ${right}`;
      }
      const p = PREC[e.op];
      return `${operand(e.left, p, 'left')} ${OPS[e.op]} ${operand(e.right, p, 'right')}`;
    }
    case 'call':
      return builtinCall(e) ?? `${e.name}(${e.args.map(expr).join(', ')})`;
  }
}

function builtinCall(e: CallExpr): string | undefined {
  const args = e.args.map(expr);
  switch (e.name) {
    case 'len':
      return `${postfixTarget(e.args[0])}.length`;
    case 'abs':
    case 'sqrt':
    case 'floor':
    case 'ceil':
    case 'round':
    case 'min':
    case 'max':
    case 'pow':
      return `Math.${e.name}(${args.join(', ')})`;
    case 'toInt':
      return `parseInt(${args[0]}, 10)`;
    case 'toReal':
      return `parseFloat(${args[0]})`;
    case 'toString':
      return `String(${args[0]})`;
    case 'upper':
      return `${postfixTarget(e.args[0])}.toUpperCase()`;
    case 'lower':
      return `${postfixTarget(e.args[0])}.toLowerCase()`;
    default:
      return undefined;
  }
}

// ---------------------------------------------------------------------------
// Helpers

export class Emitter {
  private readonly lines: string[] = [];
  private depth = 0;

  constructor(private readonly indent: string) {}

  line(text = ''): void {
    this.lines.push(text ? this.indent.repeat(this.depth) + text : '');
  }

  block(fn: () => void): void {
    this.depth++;
    fn();
    this.depth--;
  }

  toString(): string {
    return this.lines.join('\n') + '\n';
  }
}

export function scanUsage(program: TypedProgram): { input: boolean; write: boolean; writeln: boolean } {
  const uses = { input: false, write: false, writeln: false };
  const visit = (blocks: TypedBlock[]): void => {
    for (const b of blocks) {
      switch (b.kind) {
        case 'input': uses.input = true; break;
        case 'output': if (b.newline === false) uses.write = true; else uses.writeln = true; break;
        case 'if': visit(b.then); visit(b.else); break;
        case 'while': case 'doWhile': case 'for': visit(b.body); break;
        default: break;
      }
    }
  };
  visit(program.main);
  for (const fn of program.functions) visit(fn.body);
  return uses;
}
