import type { BinaryOp, CallExpr, Expr } from '../ast';
import type { CompiledProgram } from '../bytecode';
import type { BaseType, TypedBlock } from '../ir';
import { Emitter } from './js';

export interface PythonOptions {
  indent?: string;
}

/**
 * Python 3 generator.
 *
 * Where Python's own semantics differ from the interpreter (and from JS/C#/C++), the
 * generated program carries a small prelude rather than silently behaving differently:
 *
 *   fmt(value)   prints floats, bools and ints the way the interpreter does
 *                ("5" not "5.0", "true" not "True"); only emitted when needed
 *   mod(a, b)    remainder with the sign of the dividend (Python's % uses the divisor's)
 *   int(a / b)   truncating integer division (Python's // floors)
 *   math.floor(x + 0.5)   JS-style rounding (Python's round() is banker's rounding)
 */
export function generatePython(compiled: CompiledProgram, options: PythonOptions = {}): string {
  return new PythonGenerator(options.indent ?? '    ').generate(compiled);
}

interface Needs {
  math: boolean;
  fmt: boolean;
  mod: boolean;
}

/** Precedence of the emitted Python: higher binds tighter. */
const PREC: Record<BinaryOp, number> = {
  or: 1, and: 2,
  '==': 4, '!=': 4, '<': 4, '<=': 4, '>': 4, '>=': 4,
  '+': 5, '-': 5,
  '*': 6, '/': 6,
  '^': 8,
  '%': 10, div: 10, // emitted as calls
};
const NOT_PREC = 3;
const NEG_PREC = 7;
const ATOM = 10;

const OPS: Partial<Record<BinaryOp, string>> = { and: 'and', or: 'or', '^': '**' };

const isComparison = (op: BinaryOp): boolean => PREC[op] === 4;
const isStringType = (e: Expr): boolean => e.type?.kind === 'scalar' && e.type.base === 'string';
/** Only reals and bools print differently in Python; ints and strings already match the interpreter. */
const needsFmt = (e: Expr): boolean => e.type?.kind === 'scalar' && (e.type.base === 'real' || e.type.base === 'bool');

const FLIPPED: Partial<Record<BinaryOp, BinaryOp>> = { '==': '!=', '!=': '==', '<': '>=', '>=': '<', '>': '<=', '<=': '>' };
const paren = (s: string): string => `(${s})`;

function precOf(e: Expr): number {
  if (e.kind === 'binary') return PREC[e.op];
  if (e.kind === 'unary') return e.op === 'not' ? NOT_PREC : NEG_PREC;
  return ATOM;
}

class PythonGenerator {
  private readonly needs: Needs = { math: false, fmt: false, mod: false };
  private statementCount = 0;
  private current: Emitter;

  constructor(private readonly indent: string) {
    this.current = new Emitter(indent);
  }

  generate(compiled: CompiledProgram): string {
    const program = compiled.typed;
    const body = this.current;

    for (const fn of program.functions) {
      body.line(`def ${fn.name}(${fn.params.map((p) => p.name).join(', ')}):`);
      body.block(() => this.suite(fn.body));
      body.line();
      body.line();
    }
    body.line('def main():');
    body.block(() => this.suite(program.main));
    body.line();
    body.line();
    body.line('if __name__ == "__main__":');
    body.block(() => body.line('main()'));

    // The prelude depends on what the body used, so it is assembled last.
    const head = new Emitter(this.indent);
    head.line('# Generated by FlowCode — Python 3');
    if (this.needs.math || this.needs.fmt || this.needs.mod) head.line('import math');
    if (this.needs.fmt) head.line('from decimal import Decimal');
    head.line();
    head.line();
    if (this.needs.fmt) {
      for (const line of FMT_HELPER) head.line(line);
      head.line();
      head.line();
    }
    if (this.needs.mod) {
      for (const line of MOD_HELPER) head.line(line);
      head.line();
      head.line();
    }
    return head.toString() + body.toString();
  }

  // ---------------------------------------------------------------------------
  // Statements

  /** A Python block body; emits `pass` when nothing executable is inside. */
  private suite(blocks: TypedBlock[]): void {
    const before = this.statementCount;
    for (const b of blocks) this.statement(b);
    if (this.statementCount === before) this.current.line('pass');
  }

  private statement(b: TypedBlock): void {
    const out = this.current;
    if (b.kind !== 'comment') this.statementCount++;

    switch (b.kind) {
      case 'comment':
        for (const line of b.text.split('\n')) out.line(`# ${line}`);
        return;

      case 'declare':
        if (b.size) out.line(`${b.name} = [${defaultLiteral(b.type)}] * ${this.operand(b.size, 6, 'right')}`);
        else out.line(`${b.name} = ${defaultLiteral(b.type)}`);
        return;

      case 'assign':
        out.line(`${this.lvalue(b.target, b.index)} = ${this.expr(b.value)}`);
        return;

      case 'input':
        out.line(`${this.lvalue(b.target, b.index)} = ${readExpr(b.type!)}`);
        return;

      case 'output': {
        const value = this.printable(b.value);
        out.line(b.newline === false ? `print(${value}, end="")` : `print(${value})`);
        return;
      }

      case 'if': {
        out.line(`if ${this.expr(b.condition)}:`);
        out.block(() => this.suite(b.then));
        let elseBlocks = b.else;
        while (elseBlocks.length === 1 && elseBlocks[0].kind === 'if') {
          const chained = elseBlocks[0];
          out.line(`elif ${this.expr(chained.condition)}:`);
          out.block(() => this.suite(chained.then));
          elseBlocks = chained.else;
        }
        if (elseBlocks.length) {
          out.line('else:');
          out.block(() => this.suite(elseBlocks));
        }
        return;
      }

      case 'while':
        out.line(`while ${this.expr(b.condition)}:`);
        out.block(() => this.suite(b.body));
        return;

      case 'doWhile':
        // Python has no do-while: loop forever and test at the bottom.
        out.line('while True:');
        out.block(() => {
          this.suite(b.body);
          out.line(`if ${this.negated(b.condition)}:`);
          out.block(() => out.line('break'));
        });
        return;

      case 'for': {
        const step = b.step ?? 1;
        const from = this.expr(b.from);
        const stop = step > 0 ? this.plusOne(b.to) : this.minusOne(b.to);
        const args = step === 1
          ? (b.from.kind === 'num' && b.from.value === 0 ? [stop] : [from, stop])
          : [from, stop, String(step)];
        out.line(`for ${b.variable} in range(${args.join(', ')}):`);
        out.block(() => this.suite(b.body));
        return;
      }

      case 'call':
        out.line(`${b.name}(${b.args.map((a) => this.expr(a)).join(', ')})`);
        return;

      case 'break':
        out.line('break');
        return;

      case 'return':
        out.line(b.value ? `return ${this.expr(b.value)}` : 'return');
        return;
    }
  }

  private lvalue(name: string, index?: Expr): string {
    return index ? `${name}[${this.expr(index)}]` : name;
  }

  /** Strings and ints print as-is; reals and bools go through fmt() to match the interpreter. */
  private printable(e: Expr): string {
    if (!needsFmt(e)) return this.expr(e);
    this.needs.fmt = true;
    return `fmt(${this.expr(e)})`;
  }

  /** The negation of a condition, written the way a person would: `a != b` → `a == b`. */
  private negated(e: Expr): string {
    if (e.kind === 'binary' && FLIPPED[e.op]) return this.binary(FLIPPED[e.op]!, e.left, e.right, false);
    if (e.kind === 'unary' && e.op === 'not') return this.expr(e.operand);
    return `not ${this.operand(e, NOT_PREC, 'right')}`;
  }

  /** `to + 1` for range(), folding literals and `x - 1` so `range(1, n + 1)` reads naturally. */
  private plusOne(to: Expr): string {
    if (to.kind === 'num' && to.isInt) return String(to.value + 1);
    if (to.kind === 'binary' && to.op === '-' && to.right.kind === 'num' && to.right.value === 1) return this.expr(to.left);
    return `${this.operand(to, 5, 'left')} + 1`;
  }

  private minusOne(to: Expr): string {
    if (to.kind === 'num' && to.isInt) return String(to.value - 1);
    if (to.kind === 'binary' && to.op === '+' && to.right.kind === 'num' && to.right.value === 1) return this.expr(to.left);
    return `${this.operand(to, 5, 'left')} - 1`;
  }

  // ---------------------------------------------------------------------------
  // Expressions

  private operand(e: Expr, parentPrec: number, side: 'left' | 'right'): string {
    const p = precOf(e);
    const needsParens = side === 'left' ? p < parentPrec : p <= parentPrec;
    return needsParens ? paren(this.expr(e)) : this.expr(e);
  }

  private postfixTarget(e: Expr): string {
    return precOf(e) < ATOM ? paren(this.expr(e)) : this.expr(e);
  }

  private expr(e: Expr): string {
    switch (e.kind) {
      case 'num':
        return e.text;
      case 'str':
        return pythonString(e.value);
      case 'bool':
        return e.value ? 'True' : 'False';
      case 'var':
        return e.name;
      case 'index':
        return `${e.name}[${this.expr(e.index)}]`;
      case 'unary': {
        if (e.op === 'not') return `not ${this.operand(e.operand, NOT_PREC, 'right')}`;
        const doubleMinus = e.operand.kind === 'unary' && e.operand.op === '-';
        const inner = precOf(e.operand) < NEG_PREC || doubleMinus ? paren(this.expr(e.operand)) : this.expr(e.operand);
        return `-${inner}`;
      }
      case 'binary':
        return this.binary(e.op, e.left, e.right, isStringType(e));
      case 'call':
        return this.builtinCall(e) ?? `${e.name}(${e.args.map((a) => this.expr(a)).join(', ')})`;
    }
  }

  private binary(op: BinaryOp, left: Expr, right: Expr, resultIsString: boolean): string {
    switch (op) {
      case 'div':
        return `int(${this.operand(left, 6, 'left')} / ${this.operand(right, 6, 'right')})`;
      case '%':
        this.needs.mod = true;
        return `mod(${this.expr(left)}, ${this.expr(right)})`;
      case '^': {
        // ** is right-associative and binds tighter than unary minus on its left, not its right.
        const l = precOf(left) <= PREC['^'] ? paren(this.expr(left)) : this.expr(left);
        const r = precOf(right) < NEG_PREC ? paren(this.expr(right)) : this.expr(right);
        return `${l} ** ${r}`;
      }
      case '+':
        if (resultIsString) return `${this.concatOperand(left, 'left')} + ${this.concatOperand(right, 'right')}`;
        break;
      default:
        break;
    }
    const p = PREC[op];
    // Python chains comparisons (a == b == c means a == b and b == c), so a comparison
    // inside a comparison is always parenthesized.
    const leftSide = isComparison(op) ? 'right' : 'left';
    return `${this.operand(left, p, leftSide)} ${OPS[op] ?? op} ${this.operand(right, p, 'right')}`;
  }

  private concatOperand(e: Expr, side: 'left' | 'right'): string {
    if (isStringType(e)) return this.operand(e, 5, side);
    if (!needsFmt(e)) return `str(${this.expr(e)})`;
    this.needs.fmt = true;
    return `fmt(${this.expr(e)})`;
  }

  private builtinCall(e: CallExpr): string | undefined {
    const args = e.args.map((a) => this.expr(a));
    switch (e.name) {
      case 'len':
        return `len(${args[0]})`;
      case 'abs':
        return `abs(${args[0]})`;
      case 'min':
      case 'max':
        return `${e.name}(${args.join(', ')})`;
      case 'sqrt':
      case 'floor':
      case 'ceil':
      case 'pow':
        this.needs.math = true;
        return `math.${e.name}(${args.join(', ')})`;
      case 'round':
        this.needs.math = true;
        return `math.floor(${this.operand(e.args[0], 5, 'left')} + 0.5)`;
      case 'toInt':
        return `int(${args[0]})`;
      case 'toReal':
        return `float(${args[0]})`;
      case 'toString':
        this.needs.fmt = true;
        return `fmt(${args[0]})`;
      case 'upper':
        return `${this.postfixTarget(e.args[0])}.upper()`;
      case 'lower':
        return `${this.postfixTarget(e.args[0])}.lower()`;
      default:
        return undefined;
    }
  }
}

// ---------------------------------------------------------------------------
// Helpers

function defaultLiteral(type: BaseType): string {
  switch (type) {
    case 'int': return '0';
    case 'real': return '0.0';
    case 'string': return '""';
    case 'bool': return 'False';
  }
}

function readExpr(type: BaseType): string {
  switch (type) {
    case 'int': return 'int(input())';
    case 'real': return 'float(input())';
    case 'bool': return 'input().strip() == "true"';
    case 'string': return 'input()';
  }
}

/** JSON string syntax is valid Python for everything the lexer accepts (\n \t \" \\ and non-ASCII). */
function pythonString(value: string): string {
  return JSON.stringify(value);
}

const FMT_HELPER = [
  'def fmt(value):',
  '    """Format a value the way the FlowCode interpreter prints it."""',
  '    if isinstance(value, bool):',
  '        return "true" if value else "false"',
  '    if isinstance(value, float):',
  '        if value != value:',
  '            return "NaN"',
  '        if value in (math.inf, -math.inf):',
  '            return "Infinity" if value > 0 else "-Infinity"',
  '        if value == int(value) and abs(value) < 1e21:',
  '            return str(int(value))',
  '        text = repr(value)',
  '        if "e" in text:',
  '            if 1e-6 <= abs(value) < 1e21:',
  '                return format(Decimal(text), "f")',
  '            mantissa, exponent = text.split("e")',
  '            return mantissa + "e" + exponent[0] + (exponent[1:].lstrip("0") or "0")',
  '        return text',
  '    return str(value)',
];

const MOD_HELPER = [
  'def mod(a, b):',
  '    """Remainder with the sign of the dividend, like JavaScript, C# and C++."""',
  '    result = math.fmod(a, b)',
  '    return int(result) if isinstance(a, int) and isinstance(b, int) else result',
];
