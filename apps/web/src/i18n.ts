export interface I18n {
  lang: Lang;
  t: (key: StringKey, params?: Record<string, string>) => string;
  /** Localized message for a diagnostic or runtime error; `message` is the core's English text. */
  diagnostic: (code: string, message: string) => string;
}

export function makeI18n(lang: Lang): I18n {
  const table: Record<string, string> = strings[lang];
  return {
    lang,
    t: (key, params) => {
      let text = table[key] ?? strings.en[key];
      for (const [k, v] of Object.entries(params ?? {})) text = text.replace(`{${k}}`, v);
      return text;
    },
    diagnostic: (code, message) => {
      const template = (lang === 'en' ? diagnosticsEn : diagnosticsTr)[code];
      if (!template) return message;
      const quoted = /"([^"]*)"/.exec(message)?.[1] ?? '';
      return template.replace('{0}', quoted);
    },
  };
}

export const I18nContext = createContext<I18n>(makeI18n('en'));
export const useI18n = (): I18n => useContext(I18nContext);

export function detectLang(): Lang {
  const saved = localStorage.getItem('flowcode.lang');
  if (saved === 'en' || saved === 'tr') return saved;
  return navigator.language.toLowerCase().startsWith('tr') ? 'tr' : 'en';
}
